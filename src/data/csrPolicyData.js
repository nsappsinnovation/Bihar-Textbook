// The admin-saved content (setting "csr_policy_content"), or null when nothing is saved / on error
export const loadSavedCsrPolicy = () =>
  getSetting('csr_policy_content')
    .then((saved) => (saved && typeof saved === 'object' ? saved : null))
    .catch(() => null);

